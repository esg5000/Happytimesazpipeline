export type ImageSourcingResult = {
  query: string;
  /** Which provider actually produced this image — the real, honest answer, not an assumption. */
  source: 'unsplash' | 'gpt-image-1';
  photoId: string;
  /**
   * A real hosted URL for the unsplash path. Empty string for gpt-image-1
   * — that provider returns no URL, only raw bytes (see imageBase64).
   * Deliberately kept as a required string (not optional) so existing
   * downstream consumers of this shape don't break; an empty string is
   * falsy, so an unchanged `if (heroSource?.imageUrl)`-style check
   * safely skips rather than attempting to fetch a nonexistent URL.
   */
  imageUrl: string;
  /** Present for the gpt-image-1 path — raw generated image bytes, base64-encoded. Absent for unsplash. */
  imageBase64?: string;
  /** Real name for unsplash; 'AI-generated (gpt-image-1)' for the fallback — never stale Unsplash-shaped metadata carried over. */
  photographerName: string;
  /** Real profile URL for unsplash; empty string for gpt-image-1 (no profile to link). */
  photographerProfileUrl: string;
  altText: string;
  /** Unsplash-ToS-specific requirement — always false for gpt-image-1 (nothing to trigger). */
  downloadTriggerFired: boolean;
  /**
   * True if some rung of the query ladder actually passed the relevance
   * filter; false if every rung's results were off-topic and this result
   * is the resolution-only fallback pick. Always true for gpt-image-1
   * (generated directly from the structured input, nothing to mismatch).
   */
  matchedRelevanceFilter: boolean;
};

export type ImageSourcingOutcome =
  | { status: 'ok'; result: ImageSourcingResult }
  | { status: 'no-key' }
  /** Fires only when BOTH the Unsplash ladder AND the gpt-image-1 fallback fail. */
  | { status: 'no-image'; query: string }
  | { status: 'rate-limited'; query: string; httpStatus: number }
  | { status: 'error'; query: string; message: string };

