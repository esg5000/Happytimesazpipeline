type SearchUnsplashOutcome =
  | { outcome: 'ok'; results: UnsplashPhotoRow[] }
  | { outcome: 'no-results'; httpStatus?: number }
  | { outcome: 'rate-limited'; httpStatus: number }
  | { outcome: 'error'; message: string };

async function searchUnsplashOnce(query: string, key: string): Promise<SearchUnsplashOutcome> {
  let res;
  try {
    res = await axios.get<UnsplashSearchResponse>(UNSPLASH_SEARCH, {
      params: { query, per_page: 15, orientation: 'landscape' },
      headers: { Authorization: `Client-ID ${key}` },
      timeout: 20_000,
      validateStatus: () => true,
    });
  } catch (err: unknown) {
    return { outcome: 'error', message: err instanceof Error ? err.message : String(err) };
  }

  if (res.status === 403 || res.status === 429) {
    return { outcome: 'rate-limited', httpStatus: res.status };
  }

  if (res.status !== 200 || !res.data?.results?.length) {
    return { outcome: 'no-results', httpStatus: res.status };
  }

  return { outcome: 'ok', results: res.data.results };
}

// ---------------------------------------------------------------------------
// gpt-image-1 fallback — fires only when the Unsplash ladder is genuinely
// exhausted with zero results. Same structured-input discipline as the
// Unsplash query construction: built from entity/tags/section, never the
// raw headline.
// ---------------------------------------------------------------------------

function buildImageGenerationPrompt(input: ImageSourcingInput): string {
  const subjectParts = [input.entity, ...input.tags].filter((s): s is string => Boolean(s && s.trim()));
  const subject = subjectParts.length > 0 ? subjectParts.slice(0, MAX_QUERY_TERMS).join(', ') : input.section;
  return `Photorealistic editorial photograph for a Phoenix, Arizona local lifestyle news site. Subject: ${subject}. Section: ${input.section}. No overlaid text, no watermarks, no logos.`;
}

function buildAiAltText(input: ImageSourcingInput): string {
  const subject = input.entity || input.tags[0] || input.section;
  return `AI-generated editorial image related to ${subject}`;
}

/** Same endpoint/model/size/quality/n/b64_json shape as agents/imageAgent.ts's generateImage — ported, not imported, per this file's standalone pattern. */
async function generateImageWithGptImage1(prompt: string): Promise<Buffer | null> {
  const key = config.openai.apiKey;
  if (!key) {
    console.warn('[image-sourcing] gpt-image-1 fallback skipped — OPENAI_API_KEY not set. Trying Gemini…');
    return await generateImageGemini(prompt);
  }
  try {
    const res = await axios.post(
      OPENAI_IMAGES_URL,
      { model: GPT_IMAGE_MODEL, prompt, size: '1024x1024', quality: 'medium', n: 1 },
      {
        headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
        timeout: 120_000,
        validateStatus: () => true,
      }
    );
    if (res.status >= 400) {
      const data = res.data;
      const msg =
        typeof data === 'object' && data && 'error' in (data as object)
          ? JSON.stringify((data as { error?: unknown }).error)
          : res.statusText || String(res.status);
      console.warn(`[image-sourcing] gpt-image-1 call failed: HTTP ${res.status} — ${msg}; trying Gemini…`);
      return await generateImageGemini(prompt);
    }
    const b64 = res.data?.data?.[0]?.b64_json;
    if (typeof b64 !== 'string' || !b64) {
      console.warn('[image-sourcing] gpt-image-1 response had no usable b64_json; trying Gemini…');
      return await generateImageGemini(prompt);
    }
    return Buffer.from(b64, 'base64');
  } catch (err: unknown) {
    console.warn('[image-sourcing] gpt-image-1 call threw:', err instanceof Error ? err.message : String(err), '; trying Gemini…');
    return await generateImageGemini(prompt);
  }
}

/**
 * Tries buildQueryLadder()'s rungs in order (most specific first), looking
 * for the first rung whose results actually pass the relevance filter
 * (pickRelevantHighestResolutionPhoto) — a rung with results that are all
 * off-topic no longer wins just because it's the most specific rung. Only
 * if NO rung in the whole ladder produces a relevance-filter match does
 * this fall back to a resolution-only pick, from the earliest rung that
 * had any usable results — logged clearly, same "always produce something,
 * but say so" pattern as unsplashHero.ts's plain fallback. Stops
 * immediately on a rate-limit/quota response or a network error — never
 * retries past that, per the build spec.
 */
export async function sourceImage(input: ImageSourcingInput): Promise<ImageSourcingOutcome> {
  const key = config.unsplash.accessKey;
  if (!key) {
    console.error('[image-sourcing] STOPPING — UNSPLASH_ACCESS_KEY not set. Not guessing/hardcoding a key.');
    return { status: 'no-key' };
  }

  const ladder = buildQueryLadder(input);
  console.log(`[image-sourcing] "${input.title}" → query ladder: ${JSON.stringify(ladder)}`);

  let query = ladder[0]!.query;
  let photo: UnsplashPhotoRow | null = null;
  let matchedRelevanceFilter = false;
  let fallback: { query: string; photo: UnsplashPhotoRow } | null = null;

  for (const candidate of ladder) {
    const attempt = await searchUnsplashOnce(candidate.query, key);
    if (attempt.outcome === 'rate-limited') {
      console.error(`[image-sourcing] STOPPING — Unsplash rate-limit/quota response (HTTP ${attempt.httpStatus}). Not retrying.`);
      return { status: 'rate-limited', query: candidate.query, httpStatus: attempt.httpStatus! };
    }
    if (attempt.outcome === 'error') {
      console.error(`[image-sourcing] Unsplash search call threw: ${attempt.message}`);
      return { status: 'error', query: candidate.query, message: attempt.message! };
    }
    if (attempt.outcome === 'no-results') {
      console.log(`[image-sourcing] rung "${candidate.query}" → no results, trying next rung if any`);
      continue;
    }

    const picked = pickRelevantHighestResolutionPhoto(attempt.results, candidate.query, candidate.requiredTerms);
    if (!picked.photo?.urls) {
      console.log(`[image-sourcing] rung "${candidate.query}" → results had no usable photo URLs, trying next rung if any`);
      continue;
    }
    if (!fallback) {
      fallback = { query: candidate.query, photo: picked.photo };
    }
    if (picked.matchedRelevanceFilter) {
      query = candidate.query;
      photo = picked.photo;
      matchedRelevanceFilter = true;
      console.log(`[image-sourcing] rung "${candidate.query}" → matched (relevance filter satisfied)`);
      break;
    }
    console.log(`[image-sourcing] rung "${candidate.query}" → results found but none matched the relevance filter, trying next rung if any`);
  }

  if (!photo && fallback) {
    console.warn(
      `[image-sourcing] No rung in the ladder produced a relevance-filter match. Falling back to resolution-only pick from rung "${fallback.query}" (ladder tried: ${JSON.stringify(ladder)}).`
    );
    query = fallback.query;
    photo = fallback.photo;
  }

  // Confirmed bug (Ketel Marte casino articles, this morning): this used
  // to be `if (!photo)` only — a rung with results but zero relevance
  // matches still set `photo` from the resolution-only fallback above,
  // so gpt-image-1 was never tried and a mismatched photo (three women
  // running, for a "sports" query with no relevant results) got used
  // silently. Now triggers on EITHER a genuinely empty ladder (photo still
  // null) OR a ladder that returned photos but never a relevance match.
  if (!photo || !matchedRelevanceFilter) {
    const reason = !photo
      ? 'Exhausted query ladder with no results'
      : 'No rung produced a relevance-filter match (best available was a resolution-only pick)';
    console.warn(`[image-sourcing] ${reason}. Ladder tried: ${JSON.stringify(ladder)} — trying gpt-image-1.`);

    const genPrompt = buildImageGenerationPrompt(input);
    const genBuffer = await generateImageWithGptImage1(genPrompt);
    if (genBuffer) {
      const result: ImageSourcingResult = {
        query: genPrompt,
        source: 'gpt-image-1',
        photoId: `gpt-image-1-${Date.now()}`,
        imageUrl: '',
        imageBase64: genBuffer.toString('base64'),
        photographerName: 'AI-generated (gpt-image-1)',
        photographerProfileUrl: '',
        altText: buildAiAltText(input),
        downloadTriggerFired: false,
        matchedRelevanceFilter: true,
      };
      console.log(`[image-sourcing] gpt-image-1 fallback succeeded — generated ${genBuffer.length} bytes.`);
      return { status: 'ok', result };
    }

    if (!photo) {
      console.warn('[image-sourcing] gpt-image-1 fallback also failed — no image available from any source.');
      return { status: 'no-image', query };
    }
    console.warn('[image-sourcing] gpt-image-1 fallback also failed — using the irrelevant resolution-only Unsplash pick as last resort.');
  }

  const imageUrl = photo.urls?.raw || photo.urls?.full || photo.urls?.regular || '';

  let downloadTriggerFired = false;
  const downloadLoc = photo.links?.download_location;
  if (downloadLoc) {
    const trig = await triggerUnsplashDownload(downloadLoc, key);
    downloadTriggerFired = trig.fired;
    console.log(`[image-sourcing] download-trigger call → fired=${trig.fired}, httpStatus=${trig.httpStatus ?? '(threw)'}`);
  } else {
    console.warn('[image-sourcing] Selected photo has no links.download_location — cannot fire required download-trigger call.');
  }

  const result: ImageSourcingResult = {
    query,
    source: 'unsplash',
    photoId: photo.id || '(unknown)',
    imageUrl,
    photographerName: photo.user?.name || '(unknown photographer)',
    photographerProfileUrl: photo.user?.links?.html || '',
    altText: buildAltText(photo, query),
    downloadTriggerFired,
    matchedRelevanceFilter,
  };

  console.log(
    `[image-sourcing] selected photoId=${result.photoId} photographer="${result.photographerName}" downloadTriggerFired=${downloadTriggerFired} matchedRelevanceFilter=${matchedRelevanceFilter}`
  );
  return { status: 'ok', result };
}

